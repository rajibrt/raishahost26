#!/usr/bin/env node
// Builds the parts of the WHMCS theme (whmcs/templates/raishahost) that come from src/data/plans.ts,
// so plan names, taglines and specs stay the same on raishahost.com and hosting.raishahost.com.
// Prices are NOT written here: the theme shows the live WHMCS price, and `npm run check:prices`
// makes sure WHMCS and plans.ts agree.
//
// Run: npm run whmcs:build   (then upload with the steps in whmcs/README.md)

import { writeFileSync, readFileSync, mkdirSync, rmSync, existsSync } from 'node:fs'
import { createHash } from 'node:crypto'
import { execFileSync } from 'node:child_process'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { sharedHostingPlans, vpsPlans, sharedCommonFeatures, vpsCommonFeatures } from '../src/data/plans.ts'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const theme = join(root, 'whmcs/templates/raishahost')

const q = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`
const arr = (items) => `[${items.join(',')}]`

const planEntry = (p) =>
  `${p.whmcsPid}=>[${[
    `'name'=>${q(p.name)}`,
    `'tag'=>${q(p.tagline ?? '')}`,
    `'pop'=>${p.featured ? 1 : 0}`,
    `'was'=>${q(p.price.bdtOriginal ? '৳' + p.price.bdtOriginal.toLocaleString('en-IN') : '')}`,
    `'specs'=>${arr(p.specs.map((s) => arr([q(s.label), q(s.value)])))}`,
  ].join(',')}]`

const g = (name, value) => `{assign var=${name} value=${value} scope='global'}`
const out = `{* Generated by scripts/build-whmcs-theme.mjs from src/data/plans.ts. Do not edit by hand.
   Assigned with scope='global' so the page that includes this file can read the values. *}
${g('rhShared', `[${sharedHostingPlans.map(planEntry).join(',')}]`)}
${g('rhVps', `[${vpsPlans.map(planEntry).join(',')}]`)}
${g('rhSharedOrder', arr(sharedHostingPlans.map((p) => p.whmcsPid)))}
${g('rhVpsOrder', arr(vpsPlans.map((p) => p.whmcsPid)))}
${g('rhSharedCommon', arr(sharedCommonFeatures.map(q)))}
${g('rhVpsCommon', arr(vpsCommonFeatures.map(q)))}
`
mkdirSync(join(theme, 'includes'), { recursive: true })
writeFileSync(join(theme, 'includes/rh-plans.tpl'), out)
console.log('wrote whmcs/templates/raishahost/includes/rh-plans.tpl')

// Cache busting: stamp each CSS/JS link with a hash of the file, so browsers load the new file after an upload.
const stamp = (tpl, asset) => {
  const file = join(root, 'whmcs/templates', tpl)
  const hash = createHash('sha1').update(readFileSync(join(root, 'whmcs/templates', asset))).digest('hex').slice(0, 8)
  const name = asset.split('/').pop().replace('.', '\\.')
  const src = readFileSync(file, 'utf8')
  writeFileSync(file, src.replace(new RegExp(`(${name}\\?v=\\{\\$versionHash\\}-rh)[0-9a-f]*`), `$1${hash}`))
}
stamp('raishahost/includes/head.tpl', 'raishahost/css/custom.css')
stamp('raishahost/footer.tpl', 'raishahost/js/rh.js')

// Zip for upload: both template folders, paths relative to the WHMCS root.
const zip = join(root, 'whmcs/dist/raishahost-whmcs-theme.zip')
mkdirSync(dirname(zip), { recursive: true })
if (existsSync(zip)) rmSync(zip)
execFileSync('zip', ['-qr', zip, 'templates/raishahost', 'templates/orderforms/raishahost_cart', '-x', '*.DS_Store'], { cwd: join(root, 'whmcs') })
console.log('wrote whmcs/dist/raishahost-whmcs-theme.zip')
